_fb8_buf = bytearray(8)
_fb8 = framebuf.FrameBuffer(_fb8_buf, 8, 8, framebuf.MONO_VLSB)


def _draw_char8(display, ch, x, y, color=1):
    o = (ord(ch) - 0x20) * 8
    if o < 0 or o + 8 > len(_FONT8_DATA):
        return
    for c in range(8):
        v = 0
        mask = 0x80 >> c
        for r in range(8):
            if _FONT8_DATA[o + r] & mask:
                v |= 1 << r
        _fb8_buf[c] = v if color else v ^ 0xFF
    display.blit(_fb8, x, y, 0 if color else 1)


def _draw_text8(display, s, x, y, color=1):
    for ch in s:
        if x + 8 > SCR_W:
            break
        _draw_char8(display, ch, x, y, color)
        x += 8


_menu_font = None

def _init_menu_font(font_path):
    global _menu_font
    if _menu_font is not None and _menu_font.get('path') == font_path:
        return _menu_font['FW'], _menu_font['FH'], _menu_font['FB']
    try:
        from reader import _load_font, _read_exact
        meta = _load_font(font_path)
        FB = meta['char_bytes']
        FW = FH = 12 if FB == 24 else 16
        fb_buf = bytearray(FB)
        fb = framebuf.FrameBuffer(fb_buf, FW, FH, framebuf.MONO_VLSB)
        inv_buf = bytearray(FB)
        inv_fb = framebuf.FrameBuffer(inv_buf, FW, FH, framebuf.MONO_VLSB)
        _menu_font = {
            'path': font_path,
            'FW': FW, 'FH': FH, 'FB': FB,
            'fb_buf': fb_buf, 'fb': fb,
            'inv_buf': inv_buf, 'inv_fb': inv_fb,
        }
        return FW, FH, FB
    except Exception:
        _menu_font = None
        return None


def _draw_text_mixed(display, s, x, y_row, row_h, color, font_path):
    from reader import _get_glyph
    info = _init_menu_font(font_path)
    if info is None:
        _draw_text8(display, s, x, y_row + (row_h - 8) // 2, color)
        return
    FW, FH, FB = info
    fb_buf = _menu_font['fb_buf']
    fb = _menu_font['fb']
    inv_buf = _menu_font['inv_buf']
    inv_fb = _menu_font['inv_fb']
    y_as = y_row + (row_h - 8) // 2
    y_cn = y_row + (row_h - FH) // 2
    cx = x
    for ch in s:
        cp = ord(ch)
        if 0x20 <= cp <= 0x7E:
            if cx + 8 > SCR_W:
                break
            _draw_char8(display, ch, cx, y_as, color)
            cx += 8
        else:
            if cx + FW > SCR_W:
                break
            glyph = _get_glyph(font_path, ch, FB)
            if color == 0:
                for j in range(FB):
                    inv_buf[j] = glyph[j] ^ 0xFF
                display.blit(inv_fb, cx, y_cn, 1)
            else:
                fb_buf[:] = glyph
                display.blit(fb, cx, y_cn, 0)
            cx += FW


def _load_book_map():
    mapping = {}
    try:
        with open(MAP_FILE, 'r') as f:
            for line in f:
                line = line.strip()
                if '|' in line:
                    k, v = line.split('|', 1)
                    mapping[k] = v
    except Exception:
        pass
    return mapping


def list_books():
    try:
        files = os.listdir(BOOKS_DIR)
    except (OSError, UnicodeError):
        return []
    book_map = _load_book_map()
    books = []
    for f in files:
        if not isinstance(f, str) or f.startswith('.'):
            continue
        if not f.lower().endswith('.txt'):
            continue
        display = book_map.get(f, f[:-4])
        books.append(('%s/%s' % (BOOKS_DIR, f), display))
    books.sort(key=lambda x: x[0])
    return books


def list_fonts():
    fonts = []
    try:
        files = os.listdir(FONTS_DIR)
    except (OSError, UnicodeError):
        return []
    for f in files:
        try:
            if not isinstance(f, str):
                continue
            if f.endswith('.font') or f.endswith('.FONT'):
                base = f[:-5]
                for sep in range(len(base)):
                    if base[sep:].isdigit():
                        size = int(base[sep:])
                        fname = base[:sep]
                        if size in (12, 16):
                            fonts.append((fname, size))
                        break
        except Exception:
            continue
    fonts.sort()
    return fonts


def _load_settings():
    try:
        with open(SETTINGS_FILE, 'r') as f:
            line = f.read().strip()
            if line:
                parts = line.split(',')
                if len(parts) == 2:
                    return (parts[0], int(parts[1]))
    except:
        pass
    return None


def _save_settings(name, size):
    try:
        with open(SETTINGS_FILE, 'w') as f:
            f.write('%s,%d' % (name, size))
    except:
        pass


class Menu:
    def __init__(self, display, btn_up, btn_down, btn_ok):
        self.display = display
        self.btn_up = btn_up
        self.btn_down = btn_down
        self.btn_ok = btn_ok
        self.books = list_books()
        self.fonts = list_fonts()
        s = _load_settings()
        if s and s in self.fonts:
            self.font_name, self.font_size = s
        elif self.fonts:
            self.font_name, self.font_size = self.fonts[0]
        else:
            self.font_name, self.font_size = 'simsun', 12
        self._items = []
        for path, display in self.books:
            self._items.append({'type': 'book', 'path': path, 'name': display})
        self._items.append({'type': 'font'})
        self.sel = 0
        self._show()

    def _font_path(self):
        return '%s/%s%d.font' % (FONTS_DIR, self.font_name, self.font_size)

    def _show(self):
        d = self.display
        d.fill(0)
        font_path = self._font_path()
        row_h = 12 if self.font_size == 12 else 16
        rows = 48 // row_h
        for i in range(rows):
            idx = (self.sel // rows) * rows + i
            if idx >= len(self._items):
                break
            y = i * row_h
            item = self._items[idx]
            if idx == self.sel:
                d.fill_rect(0, y, SCR_W, row_h, 1)
                color = 0
            else:
                color = 1
            if item['type'] == 'book':
                _draw_text8(d, '%d.' % (idx + 1), 0, y + (row_h - 8) // 2, color)
                _draw_text_mixed(d, item['name'], 16, y, row_h, color, font_path)
            elif item['type'] == 'font':
                _draw_text_mixed(d, '>切换字体', 0, y, row_h, color, font_path)
        d.show()

    def _show_font_picker(self):
        if not self.fonts:
            return
        idx = -1
        for i, f in enumerate(self.fonts):
            if f == (self.font_name, self.font_size):
                idx = i
                break
        if idx < 0:
            idx = 0
        d = self.display
        while self.btn_ok.value() == 0:
            time.sleep_ms(10)
        time.sleep_ms(50)
        row_h = 14
        rows = 3
        y0 = 2
        while True:
            d.fill(0)
            for i in range(rows):
                fi = (idx // rows) * rows + i
                if fi >= len(self.fonts):
                    break
                y = y0 + i * row_h
                if fi == idx:
                    d.fill_rect(0, y, SCR_W, row_h, 1)
                    color = 0
                else:
                    color = 1
                _draw_text8(d, '%s%d' % self.fonts[fi], 8, y + (row_h - 8) // 2, color)
            d.show()
            while True:
                if self.btn_up.value() == 0:
                    time.sleep_ms(30)
                    if self.btn_up.value() == 0:
                        idx = (idx - 1) % len(self.fonts)
                        while self.btn_up.value() == 0:
                            time.sleep_ms(10)
                        break
                if self.btn_down.value() == 0:
                    time.sleep_ms(30)
                    if self.btn_down.value() == 0:
                        idx = (idx + 1) % len(self.fonts)
                        while self.btn_down.value() == 0:
                            time.sleep_ms(10)
                        break
                if self.btn_ok.value() == 0:
                    time.sleep_ms(30)
                    if self.btn_ok.value() == 0:
                        while self.btn_ok.value() == 0:
                            time.sleep_ms(10)
                        self.font_name, self.font_size = self.fonts[idx]
                        _save_settings(self.font_name, self.font_size)
                        return
                _idle(15)

    def run(self):
        DEBOUNCE = 30
        IDLE_POWEROFF_MS = 120000
        last_active = time.ticks_ms()
        sleeping = False
        while True:
            if self.btn_up.value() == 0 or self.btn_down.value() == 0 or self.btn_ok.value() == 0:
                last_active = time.ticks_ms()
                sleeping = False
            now = time.ticks_ms()
            if not sleeping and time.ticks_diff(now, last_active) > IDLE_POWEROFF_MS:
                self.display.writeCMD(0x28 | 0x00)
                self.display.poweroff()
                sleeping = True
            if sleeping:
                if self.btn_up.value() == 0 or self.btn_down.value() == 0 or self.btn_ok.value() == 0:
                    self.display.writeCMD(0x28 | 0x07)
                    self.display.poweron()
                    self._show()
                    sleeping = False
                _idle(50)
                continue
            if self.btn_up.value() == 0:
                time.sleep_ms(DEBOUNCE)
                if self.btn_up.value() == 0:
                    if self.sel > 0:
                        self.sel -= 1
                        self._show()
                    while self.btn_up.value() == 0:
                        time.sleep_ms(10)
            if self.btn_down.value() == 0:
                time.sleep_ms(DEBOUNCE)
                if self.btn_down.value() == 0:
                    if self.sel < len(self._items) - 1:
                        self.sel += 1
                        self._show()
                    while self.btn_down.value() == 0:
                        time.sleep_ms(10)
            if self.btn_ok.value() == 0:
                time.sleep_ms(DEBOUNCE)
                if self.btn_ok.value() == 0:
                    if self._items[self.sel]['type'] == 'font':
                        self._show_font_picker()
                        self._show()
                    elif self.books:
                        return (
                            self._items[self.sel]['path'],
                            '%s/%s%d.font' % (FONTS_DIR, self.font_name, self.font_size),
                        )
            _idle(15)
